    private void btnSaveActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSaveActionPerformed
        

        if (txtMedicineID.getText().trim().isEmpty()
               || txtMedicineName.getText().trim().isEmpty()
               || cmbCategory.getSelectedIndex() == 0
               || txtQuantity.getText().trim().isEmpty()
               || txtUnitPrice.getText().trim().isEmpty()
               || txtExpiryDate.getText().trim().isEmpty()) {

            JOptionPane.showMessageDialog(this,
                   "Please fill all required fields!");
            return;
        }

        try {
            int id = Integer.parseInt(txtMedicineID.getText().trim());
            int quantity = Integer.parseInt(txtQuantity.getText().trim());
            double price = Double.parseDouble(txtUnitPrice.getText().trim());

            if (id <= 0 || quantity < 0 || price < 0) {
                JOptionPane.showMessageDialog(this,
                       "Enter valid ID, quantity and price!");
                return;
            }

            java.sql.Date expiry =
                   java.sql.Date.valueOf(txtExpiryDate.getText().trim());

            String sql = "INSERT INTO Medicines "
                   + "(MedicineID, MedicineName, Category, Quantity, "
                   + "UnitPrice, ExpiryDate, Supplier) "
                   + "VALUES (?, ?, ?, ?, ?, ?, ?)";

            try (Connection con =
                    com.petcare.database.DaBConnection.getConnection();
                    PreparedStatement pst = con.prepareStatement(sql)) {

                    pst.setInt(1, id);
                    pst.setString(2, txtMedicineName.getText().trim());
                    pst.setString(3, cmbCategory.getSelectedItem().toString());
                    pst.setInt(4, quantity);
                    pst.setDouble(5, price);
                    pst.setDate(6, expiry);
                    pst.setString(7, txtSupplier.getText().trim());

                    pst.executeUpdate();
            }

            JOptionPane.showMessageDialog(this,
                   "Medicine saved successfully!");

            
            clearFields();
 
            } catch (NumberFormatException e) {
                   JOptionPane.showMessageDialog(this,
                   "ID, quantity and price must be numbers!");
            } catch (IllegalArgumentException e) {
                   JOptionPane.showMessageDialog(this,
                   "Expiry Date format should be YYYY-MM-DD!");
            } catch (SQLException e) {
                   JOptionPane.showMessageDialog(this,
                    "Database Error: " + e.getMessage());
            }

    }//GEN-LAST:event_btnSaveActionPerformed

    private void btnDeleteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDeleteActionPerformed
            

        if (txtMedicineID.getText().trim().isEmpty()) {
            JOptionPane.showMessageDialog(this,
                 "Enter or select a Medicine ID!");
            return;
        }

        int confirm = JOptionPane.showConfirmDialog(
            this,
            "Are you sure you want to delete this medicine?",
            "Confirm Delete",
            JOptionPane.YES_NO_OPTION
        );

        if (confirm != JOptionPane.YES_OPTION) {
             return;
        }

        try {
            int id = Integer.parseInt(txtMedicineID.getText().trim());

            String sql = "DELETE FROM Medicines WHERE MedicineID=?";

            try (Connection con =
                   com.petcare.database.DaBConnection.getConnection();
                   PreparedStatement pst = con.prepareStatement(sql)) {

                   pst.setInt(1, id);

                   int rows = pst.executeUpdate();

                    if (rows > 0) {
                        JOptionPane.showMessageDialog(this,
                             "Medicine deleted successfully!");
                
                        clearFields();
                    } else {
                        JOptionPane.showMessageDialog(this,
                             "Medicine ID not found!");
                    }
            }

        } catch (NumberFormatException e) {
             JOptionPane.showMessageDialog(this,
                "Medicine ID must be a number!");
        } catch (SQLException e) {
             JOptionPane.showMessageDialog(this,
                "Database Error: " + e.getMessage());
        }

    }//GEN-LAST:event_btnDeleteActionPerformed

