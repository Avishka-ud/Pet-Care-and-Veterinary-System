    private int getCount(String sql) {
        try (Connection con = DaBConnection.getConnection();
             PreparedStatement pst = con.prepareStatement(sql);
             ResultSet rs = pst.executeQuery()) {

            if (rs.next()) {
                return rs.getInt(1);
            }
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this,
                "Error loading dashboard: " + e.getMessage());
        }
        return 0;
    }

    private void loadCounts() {
        lblTotalPets.setText(String.valueOf(
            getCount("SELECT COUNT(*) FROM pets")));

        lblTotalOwners.setText(String.valueOf(
            getCount("SELECT COUNT(*) FROM owners")));

        lblTotalVets.setText(String.valueOf(
            getCount("SELECT COUNT(*) FROM veterinarians")));

        lblAppointmentsToday.setText(String.valueOf(
            getCount("SELECT COUNT(*) FROM appointments "
                   + "WHERE DATE(AppointmentDate) = CURDATE()")));
    }

    private void loadRecentAppointments() {
        DefaultTableModel model = (DefaultTableModel) tblRecent.getModel();
        model.setRowCount(0);

        String sql = "SELECT a.AppointmentID, p.PetName, "
                   + "o.OwnerName, v.VetName, "
                   + "a.AppointmentDate, a.Status "
                   + "FROM appointments a "
                   + "JOIN pets p ON a.PetID = p.PetID "
                   + "JOIN owners o ON a.OwnerID = o.OwnerID "
                   + "JOIN veterinarians v ON a.VeterinarianID = v.VetID "
                   + "ORDER BY a.AppointmentDate DESC "
                   + "LIMIT 10";

        try (Connection con = DaBConnection.getConnection();
             PreparedStatement pst = con.prepareStatement(sql);
             ResultSet rs = pst.executeQuery()) {

            while (rs.next()) {
                model.addRow(new Object[]{
                    rs.getInt("AppointmentID"),
                    rs.getString("PetName"),
                    rs.getString("OwnerName"),
                    rs.getString("VetName"),
                    rs.getString("AppointmentDate"),
                    rs.getString("Status")
                });
            }

        } catch (Exception e) {
            JOptionPane.showMessageDialog(this,
                "Error loading appointments: " + e.getMessage());
        }
    }

