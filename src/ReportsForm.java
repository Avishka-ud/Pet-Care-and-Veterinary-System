    private void btnSearchActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSearchActionPerformed
       
    String reportType = cmbReportType.getSelectedItem().toString();
    String status = cmbStatus.getSelectedItem().toString();

    if (cmbReportType.getSelectedIndex() == 0) {
        JOptionPane.showMessageDialog(this,
                "Please select a report type.");
        return;
    }

    DefaultTableModel model =
            (DefaultTableModel) tblReports.getModel();

    model.setRowCount(0);

    try {
        Connection con = DaBConnection.getConnection();

        String sql = "SELECT AppointmentID, AppointmentDate, "
                   + "OwnerID, PetID, Status "
                   + "FROM Appointments WHERE 1=1";

        if (!status.equals("All")) {
            sql += " AND Status = ?";
        }

        if (!txtFromDate.getText().trim().isEmpty()
                && !txtToDate.getText().trim().isEmpty()) {
            sql += " AND AppointmentDate BETWEEN ? AND ?";
        }

        PreparedStatement pst = con.prepareStatement(sql);

        int index = 1;

        if (!status.equals("All")) {
            pst.setString(index++, status);
        }

        if (!txtFromDate.getText().trim().isEmpty()
                && !txtToDate.getText().trim().isEmpty()) {
            pst.setString(index++, txtFromDate.getText().trim());
            pst.setString(index++, txtToDate.getText().trim());
        }

        ResultSet rs = pst.executeQuery();

        while (rs.next()) {
            model.addRow(new Object[]{
                rs.getObject("AppointmentID"),
                rs.getObject("AppointmentDate"),
                rs.getObject("OwnerID"),
                rs.getObject("PetID"),
                rs.getObject("Status")
            });
        }

        if (model.getRowCount() == 0) {
            JOptionPane.showMessageDialog(this,
                    "No records found.");
        }

        rs.close();
        pst.close();
        con.close();

    } catch (SQLException e) {
        JOptionPane.showMessageDialog(this,
                "Search failed: " + e.getMessage());
    }

    

   
  

    }//GEN-LAST:event_btnSearchActionPerformed

