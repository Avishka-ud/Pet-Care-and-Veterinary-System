    private void btnExportPDFActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnExportPDFActionPerformed
       
       

    if (tblReports.getRowCount() == 0) {
        JOptionPane.showMessageDialog(this,
                "No report data available to export.");
        return;
    }

    javax.swing.JFileChooser chooser =
            new javax.swing.JFileChooser();

    chooser.setSelectedFile(
            new java.io.File("PetCare_Report.pdf"));

    if (chooser.showSaveDialog(this)
            != javax.swing.JFileChooser.APPROVE_OPTION) {
        return;
    }

    java.io.File file = chooser.getSelectedFile();

    if (!file.getName().toLowerCase().endsWith(".pdf")) {
        file = new java.io.File(file.getAbsolutePath() + ".pdf");
    }

    try {
        com.itextpdf.text.Document document =
                new com.itextpdf.text.Document();

        com.itextpdf.text.pdf.PdfWriter.getInstance(
                document,
                new java.io.FileOutputStream(file));

        document.open();

        com.itextpdf.text.Font titleFont =
                new com.itextpdf.text.Font(
                        com.itextpdf.text.Font.FontFamily.HELVETICA,
                        18,
                        com.itextpdf.text.Font.BOLD);

        document.add(new com.itextpdf.text.Paragraph(
                "Pet Care and Veterinary System", titleFont));

        document.add(new com.itextpdf.text.Paragraph(
                "Report Management"));

        document.add(new com.itextpdf.text.Paragraph(" "));
        
        int columns = tblReports.getColumnCount();
        
        com.itextpdf.text.pdf.PdfPTable pdfTable =
                new com.itextpdf.text.pdf.PdfPTable(columns);

        pdfTable.setWidthPercentage(100);

        for (int col = 0; col < columns; col++) {
            pdfTable.addCell(
                    tblReports.getColumnName(col));
        }

        for (int row = 0;
                row < tblReports.getRowCount(); row++) {

            for (int col = 0; col < columns; col++) {
                Object value =
                        tblReports.getValueAt(row, col);

                pdfTable.addCell(
                        value == null ? "" : value.toString());
            }
        }

        document.add(pdfTable);
        document.close();

        JOptionPane.showMessageDialog(this,
                "PDF exported successfully!");

    } catch (Exception e) {
        JOptionPane.showMessageDialog(this,
                "PDF export failed: " + e.getMessage());
    }

    }//GEN-LAST:event_btnExportPDFActionPerformed

