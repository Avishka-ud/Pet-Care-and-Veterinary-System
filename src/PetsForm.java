    private void btnUpdateActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnUpdateActionPerformed
            String sql = "UPDATE Pets SET PetName=?, PetType=?, "
            + "Breed=?, Age=?, Gender=?, OwnerID=? WHERE PetID=?";

        try (Connection con = DaBConnection.getConnection();
            PreparedStatement pst = con.prepareStatement(sql)) {

            int petID = Integer.parseInt(txtpetID.getText().trim());
            int age = Integer.parseInt(txtAge.getText().trim());
            int ownerID = Integer.parseInt(txtOwnerID.getText().trim());

            if (txtpetName.getText().trim().isEmpty()) {
                JOptionPane.showMessageDialog(this,
                     "Please enter Pet Name!");
            return;
            }

            if (age < 0) {
                JOptionPane.showMessageDialog(this,
                    "Age cannot be negative!");
            return;
            }

            pst.setString(1, txtpetName.getText().trim());
            pst.setString(2, cmbpetType.getSelectedItem().toString());
            pst.setString(3, txtBreed.getText().trim());
            pst.setInt(4, age);
            pst.setString(5, cmbGender.getSelectedItem().toString());
            pst.setInt(6, ownerID);
            pst.setInt(7, petID);

            int rows = pst.executeUpdate();

            if (rows > 0) {
                JOptionPane.showMessageDialog(this,
                    "Pet updated successfully!");
                clearFields();
            } else {
                JOptionPane.showMessageDialog(this,
                    "Pets ID not found!");
            }
        }catch(NumberFormatException e) {
            JOptionPane.showMessageDialog(this,
                "Please enter valid numbers!");

        } catch (Exception e) {
            JOptionPane.showMessageDialog(this,
                "Update failed: " + e.getMessage());
        }

            
        
    }//GEN-LAST:event_btnUpdateActionPerformed

    private void btnSaveActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSaveActionPerformed
        String petID = txtpetID.getText().trim();
        String petName = txtpetName.getText().trim();
        String breed = txtBreed.getText().trim();
        String age = txtAge.getText().trim();
        String ownerID = txtOwnerID.getText().trim();

        if (petID.isEmpty() || petName.isEmpty()
            || breed.isEmpty() || age.isEmpty()
            || ownerID.isEmpty()) {

            JOptionPane.showMessageDialog(this,
               "Please fill all pet details!");
            return;
        }

        String sql = "INSERT INTO Pets "
           + "(PetID, PetName, PetType, Breed, Age, Gender, OwnerID) "
           + "VALUES (?, ?, ?, ?, ?, ?, ?)";

        try (Connection con = DaBConnection.getConnection();
             PreparedStatement pst = con.prepareStatement(sql)) {

            pst.setInt(1, Integer.parseInt(petID));
            pst.setString(2, petName);
            pst.setString(3, cmbpetType.getSelectedItem().toString());
            pst.setString(4, breed);
            pst.setInt(5, Integer.parseInt(age));
            pst.setString(6, cmbGender.getSelectedItem().toString());
            pst.setInt(7, Integer.parseInt(ownerID));

            int result = pst.executeUpdate();

            if (result > 0) {
                JOptionPane.showMessageDialog(this,
                "Pet saved successfully!");
            clearFields();
        
                
            }

        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this,
            "Pet ID, Age and Owner ID must be numbers!");

        } catch (SQLException e) {
            JOptionPane.showMessageDialog(this,
            "Error saving pet: " + e.getMessage());
        }

    
        
        
    }//GEN-LAST:event_btnSaveActionPerformed

