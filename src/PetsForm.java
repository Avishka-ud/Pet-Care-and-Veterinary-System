    private void loadPets() {

        javax.swing.table.DefaultTableModel model =
            (javax.swing.table.DefaultTableModel) tblPets.getModel();

        model.setRowCount(0);

        String sql = "SELECT PetID, PetName, PetType, " +
                     "Breed, Gender, OwnerID," +
                     "FROM Pets";

        try {
            java.sql.Connection con =
                com.petcare.database.DaBConnection.getConnection();

            java.sql.PreparedStatement pst = con.prepareStatement(sql);
            java.sql.ResultSet rs = pst.executeQuery();

            while (rs.next()) {
                model.addRow(new Object[]{
                    rs.getInt("PetID"),
                    rs.getString("PetName"),
                    rs.getString("PetType"),
                    rs.getString("Breed"),
                    rs.getInt("Age"),
                    rs.getString("Gender"),
                    rs.getInt("OwnerID"),
                    
                });
            }

            rs.close();
            pst.close();

        } catch (Exception e) {
            javax.swing.JOptionPane.showMessageDialog(
                this, "Error loading pets: " + e.getMessage()
             );
        }
        
    }

