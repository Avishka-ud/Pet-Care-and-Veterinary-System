    private void loadAppointments() {

        javax.swing.table.DefaultTableModel model =
            (javax.swing.table.DefaultTableModel) tblAppointments.getModel();

        model.setRowCount(0);

        String sql = "SELECT AppointmentID, PetName, OwnerName, " +
            "Veterinarian, AppointmentDate, AppointmentTime, " +
            "Reason, Status FROM Appointments";

        try {
            java.sql.Connection con =
                com.petcare.database.DaBConnection.getConnection();

            java.sql.PreparedStatement pst = con.prepareStatement(sql);
            java.sql.ResultSet rs = pst.executeQuery();

            while (rs.next()) {
                model.addRow(new Object[]{
                    rs.getInt("AppointmentID"),
                    rs.getString("PetName"),
                    rs.getString("OwnerName"),
                    rs.getString("Veterinarian"),
                    rs.getDate("AppointmentDate"),
                    rs.getString("Reason"),
                    rs.getString("Status")
                });
            }

            rs.close();
            pst.close();

        } catch (Exception e) {
            javax.swing.JOptionPane.showMessageDialog(
                this, "Error loading appointments: " + e.getMessage()
             );
        }
        
    }
    
          
    

