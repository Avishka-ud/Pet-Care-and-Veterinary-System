    private void btnSaveActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSaveActionPerformed

String ownerid = txtOwnerID.getText().trim();
    String name = txtOwnerName.getText().trim();
    String phone = txtPhone.getText().trim();
    String email = txtEmail.getText().trim();
    String address = txtAddress.getText().trim();

    // 1. Owner Name validation
    if (name.isEmpty()) {
        JOptionPane.showMessageDialog(this,
                "Please enter Owner Name!");
        txtOwnerName.requestFocus();
        return;
    }

    if (!name.matches("[a-zA-Z ]+")) {
        JOptionPane.showMessageDialog(this,
                "Owner Name must contain letters only!");
        txtOwnerName.requestFocus();
        return;
    }

    // 2. Phone validation
    if (phone.isEmpty()) {
        JOptionPane.showMessageDialog(this,
                "Please enter Phone Number!");
        txtPhone.requestFocus();
        return;
    }

    if (!phone.matches("[0-9]{10}")) {
        JOptionPane.showMessageDialog(this,
                "Phone Number must contain exactly 10 digits!");
        txtPhone.requestFocus();
        return;
    }

    // 3. Email validation
    if (email.isEmpty()) {
        JOptionPane.showMessageDialog(this,
                "Please enter Email!");
        txtEmail.requestFocus();
        return;
    }

    if (!email.matches("^[A-Za-z0-9+_.-]+@[A-Za-z0-9.-]+\\.[A-Za-z]{2,}$")) {
        JOptionPane.showMessageDialog(this,
                "Please enter a valid Email Address!");
        txtEmail.requestFocus();
        return;
    }

    // 4. Address validation
    if (address.isEmpty()) {
        JOptionPane.showMessageDialog(this,
                "Please enter Address!");
        txtAddress.requestFocus();
        return;
    }

    // 5. Save data to database
    String sql = "INSERT INTO Owners "
            + "(OwnerID,OwnerName, Phone, Email, Address) "
            + "VALUES (?,?, ?, ?, ?)";

    try (Connection con = DaBConnection.getConnection();
         PreparedStatement pst = con.prepareStatement(sql)) {

        pst.setString(1, name);
        pst.setString(2, phone);
        pst.setString(3, email);
        pst.setString(4, address);

        pst.executeUpdate();

        JOptionPane.showMessageDialog(this,
                "Owner saved successfully!");

        loadOwners();
        clearFields();

    } catch (SQLException e) {
        JOptionPane.showMessageDialog(this,
                "Error saving owner: " + e.getMessage());
    }

       
    }//GEN-LAST:event_btnSaveActionPerformed

    private void btnDeleteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDeleteActionPerformed
       

    // 1. Owner ID validation
    if (txtOwnerID.getText().trim().isEmpty()) {
        JOptionPane.showMessageDialog(this,
                "Please select an owner to delete!",
                "Validation Error",
                JOptionPane.WARNING_MESSAGE);
        return;
    }

    // 2. Check Owner ID
    int ownerID;

    try {
        ownerID = Integer.parseInt(txtOwnerID.getText().trim());
    } catch (NumberFormatException e) {
        JOptionPane.showMessageDialog(this,
                "Invalid Owner ID!",
                "Validation Error",
                JOptionPane.WARNING_MESSAGE);
        return;
    }

    // 3. Confirm before deleting
    int confirm = JOptionPane.showConfirmDialog(this,
            "Are you sure you want to delete this owner?",
            "Confirm Delete",
            JOptionPane.YES_NO_OPTION,
            JOptionPane.WARNING_MESSAGE);

    if (confirm != JOptionPane.YES_OPTION) {
        return;
    }

    // 4. Delete from database
    String sql = "DELETE FROM Owners WHERE OwnerID = ?";

    try (Connection con = DaBConnection.getConnection();
         PreparedStatement pst = con.prepareStatement(sql)) {

        pst.setInt(1, ownerID);

        int result = pst.executeUpdate();

        if (result > 0) {
            JOptionPane.showMessageDialog(this,
                    "Owner deleted successfully!",
                    "Success",
                    JOptionPane.INFORMATION_MESSAGE);

            loadOwners();
            clearFields();

        } else {
            JOptionPane.showMessageDialog(this,
                    "Owner not found!",
                    "Error",
                    JOptionPane.ERROR_MESSAGE);
        }

    } catch (SQLException e) {
        JOptionPane.showMessageDialog(this,
                "Unable to delete owner. " + e.getMessage(),
                "Database Error",
                JOptionPane.ERROR_MESSAGE);
    }


    

       
           
    }//GEN-LAST:event_btnDeleteActionPerformed

